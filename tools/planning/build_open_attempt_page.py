"""Write the generated sections of the open-attempt review page from the planning package.

The page proposals/open-attempt/review-page/index.html is hand-written except for three sections,
which this script replaces between their markers, so they cannot drift from the package files:

  <!-- types:start/end -->    the metamodel types (docs/model/metamodel.graph.json + metamodel-mapping.json)
  <!-- maps:start/end -->     the domain map and the open-questions map, drawn with the shared graph viewer
  <!-- package:start/end -->  checks with counts, open questions, diagrams, cold review

The two maps are written to maps.js next to the page; the viewer script is the planning-package
page's copy (../../planning-package/review-page/graph-viewer.js).

  python3 tools/planning/build_open_attempt_page.py
"""
import html
import json
import pathlib

REPO = pathlib.Path(__file__).resolve().parents[2]
PAGE = REPO / "proposals" / "open-attempt" / "review-page"
# Links resolve on GitHub once this branch is merged; the page is served from main.
BLOB = "https://github.com/BrianMills2718/world-substrate/blob/main/"
e = html.escape


def _json(rel: str):
    return json.loads((REPO / rel).read_text(encoding="utf-8"))


def _replace(text: str, name: str, section: str) -> str:
    start, end = f"<!-- {name}:start -->", f"<!-- {name}:end -->\n"
    if start in text:
        a, b = text.index(start), text.index(end) + len(end)
        return text[:a] + section + text[b:]
    return text.replace("<h2>One choice for you</h2>", section + "<h2>One choice for you</h2>", 1)


def types_section() -> str:
    g = _json("docs/model/metamodel.graph.json")
    maps = {m["node"]: m for m in _json("docs/model/metamodel-mapping.json")["mappings"]}
    groups = [("state", "What the world holds"), ("acting", "How someone acts"),
              ("rules", "What the rules do"), ("noticing", "Who learns of it")]
    rows = []
    for kind, title in groups:
        rows.append(f'<tr><th colspan="3" class="grp">{title}</th></tr>')
        for n in (x for x in g["nodes"] if x["kind"] == kind):
            m = maps.get(n["id"], {})
            status = '<span class="tag miss">planned</span>' if n.get("dashed") else '<span class="tag have">built</span>'
            kern = e(f'{m.get("relation", "")} {m.get("maps_to", "")}'.strip()) or "—"
            rows.append(f'<tr><td><b>{e(n["label"])}</b> {status}</td><td>{e(n["explain"])}</td><td>{kern}</td></tr>')
    return f'''<!-- types:start -->
<h2>The types the world is built from</h2>
<p class="lede">Every thing, move, rule and notice the steps above use is one of these types. Blue "built" means World Substrate has it today; orange "planned" means a later slice of this plan adds it. The last column says how each one maps onto the shared scientific-hypergraph kernel (revision <code>7b0638f</code>), so the types are not a framework made up here. Before minting them, these formalisms were checked: PDDL and PDDL+ (closest: a move kind is a PDDL action, and PDDL+ has processes and events), Event Calculus (source of the knock-on design), onto-canon6, and the repository's own projection onto Linguistic Core's relation-schema.v1. The continuous-equation formats (SBML, CellML, Modelica and others) were not checked further: they hold continuous equations, and these rules are discrete checks and effects. Petri nets and TypeDB were weighed and composed rather than adopted (Q24, resolved): Petri-net transition semantics are reused for linked process participants, but neither carries per-observer noticing or named refusals. Full table: <a href="{BLOB}docs/model/METAMODEL.md">METAMODEL.md</a>.</p>
<div class="tablewrap"><table class="types"><thead><tr><th>Type</th><th>What it is</th><th>On the shared kernel</th></tr></thead><tbody>
{chr(10).join(rows)}
</tbody></table></div>
<!-- types:end -->
'''


def maps_section(domain: dict, qmap: dict) -> str:
    (PAGE / "maps.js").write_text(
        "// Generated by tools/planning/build_open_attempt_page.py from docs/model/domain.graph.json and\n"
        "// docs/model/open-questions.graph.json; do not edit.\n"
        f"window.MAPS = {json.dumps({'domain': domain, 'questions': qmap}, indent=1)};\n", encoding="utf-8")
    kinds = " · ".join(e(k["label"]) for k in domain["kinds"].values())
    return f'''<!-- maps:start -->
<h2>The maps behind the plan</h2>
<p class="lede">The domain map: every idea this plan touches, coloured by kind ({kinds}), so you can see what every world gets as substrate code and what each world writes for itself. {len(domain["nodes"])} ideas, {len(domain["edges"])} links. Drag to move, scroll to zoom, click an idea to read it. Source: <a href="{BLOB}docs/model/domain.graph.json">domain.graph.json</a>, explained in <a href="{BLOB}docs/model/DOMAIN.md">DOMAIN.md</a>.</p>
<div class="graph" id="map-domain"></div>
<p class="mapinfo" id="map-domain-info">Click an idea to see what it is and where it lives in the code.</p>
<p class="lede">The open-questions map: each open question beside the ideas it touches ({len([n for n in qmap["nodes"] if n["kind"] != "Concept"])} questions drawn). Source: <a href="{BLOB}docs/model/open-questions.graph.json">open-questions.graph.json</a>.</p>
<div class="graph" id="map-questions"></div>
<p class="mapinfo" id="map-questions-info">Click a question to read it.</p>
<!-- maps:end -->
'''


def package_section() -> str:
    pkg = _json("docs/planning/open-attempt/planning-package.json")["parts"]
    run_line = (REPO / pkg["checks"]["path"]).read_text(encoding="utf-8").splitlines()[0].rstrip(".")
    qs = _json(pkg["open_questions"]["path"])["questions"]
    check_rows = []
    for r in pkg["checks"]["results"]:
        ok = r["exit_status"] == 0
        tag = '<span class="tag have">exit 0</span>' if ok else f'<span class="tag miss">exit {r["exit_status"]}</span>'
        note = f' (tracked as {r["tracked_by"]})' if r.get("tracked_by") else ""
        counts = ", ".join(f"{k.replace('_', ' ')} {v}" for k, v in r["counts"].items())
        check_rows.append(f'<tr><td>{e(r["name"])}</td><td>{e(counts)}{e(note)}</td><td>{tag}</td></tr>')
    open_q = [q for q in qs if q["status"] == "open"]
    resolved = len(qs) - len(open_q)
    q_rows = [f'<tr><td><b>{e(q["id"])}</b> {e(q["short"])}</td><td>{"Brian" if q["owner"] == "brian" else "agent"}</td>'
              f'<td>{e(q["blocks"])}</td></tr>' for q in open_q]
    diag = "".join(f'<li><a href="{BLOB}{e(d["path"])}">{e(pathlib.Path(d["path"]).name)}</a>: {e(d["question"])}</li>'
                   for d in pkg["diagrams"]["items"])
    return f'''<!-- package:start -->
<h2>The planning package behind this page</h2>
<p class="lede">The repository's checks, its open questions and its diagrams, from <a href="{BLOB}docs/planning/open-attempt/planning-package.json">planning-package.json</a>. Check results are from <a href="{BLOB}{e(pkg["checks"]["path"])}">checks.txt</a> ({e(run_line)}); orange marks a check that does not pass. Links to GitHub point at the main branch, so files this change adds open only after it merges.</p>
<div class="tablewrap"><table class="pkg"><thead><tr><th>Check</th><th>Counts</th><th>Result</th></tr></thead><tbody>
{chr(10).join(check_rows)}
</tbody></table></div>
<h3 class="sub">Open questions: {len(open_q)} open, {resolved} resolved</h3>
<p class="lede">Each open question and the decision it blocks (<a href="{BLOB}{e(pkg["open_questions"]["path"])}">open-questions.json</a>). "Agent" means checking or reading can settle it; "Brian" means it is a product call.</p>
<div class="tablewrap"><table class="qs"><thead><tr><th>Question</th><th>Whose call</th><th>Blocks</th></tr></thead><tbody>
{chr(10).join(q_rows)}
</tbody></table></div>
<h3 class="sub">Diagrams</h3>
<ul class="plain">{diag}</ul>
<p>Cold review of this package: <a href="{BLOB}{e(pkg["cold_review"]["path"])}">cold-review.md</a>.</p>
<!-- package:end -->
''', len(check_rows), len(open_q), resolved


def main() -> None:
    domain = _json("docs/model/domain.graph.json")
    qmap = _json("docs/model/open-questions.graph.json")
    page = PAGE / "index.html"
    text = page.read_text(encoding="utf-8")
    text = _replace(text, "types", types_section())
    text = _replace(text, "maps", maps_section(domain, qmap))
    package, n_checks, n_open, n_resolved = package_section()
    text = _replace(text, "package", package)
    page.write_text(text, encoding="utf-8")
    print(f"open-attempt page: {n_checks} checks, {n_open} open and {n_resolved} resolved questions, "
          f"domain map {len(domain['nodes'])} nodes, questions map {len(qmap['nodes'])} nodes")


if __name__ == "__main__":
    main()
