"""Decision 007 proof of concept (docs/plans/any_scenario_poc.md): deterministic checks over recorded evidence.

No model calls. The truck world under spikes/any-scenario-2026-10/evidence/truck was generated by the
layer-1 pipeline (ODD -> bundle -> mechanics -> checks -> rule-writer repairs); the run is the recorded
LLM-resident run with the station's fuel set to zero, in which the game master wrote rules mid-run.
"""
